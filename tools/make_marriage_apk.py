"""Build a signed, installable split APK set for Marriage with the patched Hermes bundle.

Uses the repo's own graft/align/sign helpers (tools/common.py, tools/patch.py) so the
result follows the same contract as tools/patch.py: original split structure preserved,
every split signed with one stable key, CRC-safe archive rewrite, 4-byte alignment.
"""
from __future__ import annotations
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import patch as P
from common import APKS_DIR, rebundle_apk, zip_entries

SRC_DIR = APKS_DIR / "marriage"
OUT_DIR = APKS_DIR / "marriage-patched"
PATCHED_BUNDLE = APKS_DIR / "extracted" / "marriage" / "assets" / "index.android.bundle.advantage"

def main() -> int:
    if not SRC_DIR.is_dir():
        raise SystemExit(f"missing {SRC_DIR}")
    if not PATCHED_BUNDLE.exists():
        raise SystemExit(f"missing patched bundle {PATCHED_BUNDLE}")

    splits = sorted(SRC_DIR.glob("*.apk"))
    base = next((p for p in splits if p.name == "base.apk"), None)
    if base is None:
        raise SystemExit("base.apk not found in split set")
    others = [p for p in splits if p is not base]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    work = OUT_DIR / "work"
    work.mkdir(parents=True, exist_ok=True)

    signing = P.ensure_keystore()
    print(f"signing key: {signing.path.name} (alias {signing.alias})")

    patched_bytes = PATCHED_BUNDLE.read_bytes()
    replacements = {"assets/index.android.bundle": patched_bytes}

    # base split: graft the changed entry
    base_unsigned = work / "base.patched-unsigned.apk"
    changed = rebundle_apk(base, base_unsigned, replacements)
    print(f"base: grafted {changed}")
    if "assets/index.android.bundle" not in changed:
        raise SystemExit("graft did not land in base.apk")

    outputs = []
    # base
    out_base = OUT_DIR / "base.apk"
    P.align_and_sign(base_unsigned, out_base, signing, work)
    print(f"signed {out_base.name}  {out_base.stat().st_size:,} bytes  [{P.verify_signature(out_base)}]")
    outputs.append(out_base)

    # other splits: unchanged bytes, re-align + re-sign with the same key
    for split in others:
        out = OUT_DIR / split.name
        P.align_and_sign(split, out, signing, work)
        print(f"signed {out.name}  {out.stat().st_size:,} bytes  [{P.verify_signature(out)}]")
        outputs.append(out)

    # manifest
    import json
    (OUT_DIR / "MANIFEST.md").write_text(
        "# Patched build manifest (generated by tools/make_marriage_apk.py)\n\n"
        "- package: `com.bhoos.marriage`\n"
        "- changes: Hermes bundle patched (2 length-preserving edits: hourly-gift countdown\n"
        "  bypass, rewarded-ad load-failure grants the reward). Patches 1-5 of the earlier\n"
        "  \"upper hand\" set (deck/show-cards unmask, joker, free Card Tracker) are discarded:\n"
        "  they only bite when the device runs the engine, not in real multiplayer.\n"
        "- signing key: `%s` alias `%s`\n\n"
        "## Output APKs\n\n| file | bytes |\n|---|---|\n"
        % (signing.path.name, signing.alias)
        + "".join(f"| `{o.name}` | {o.stat().st_size:,} |\n" for o in outputs)
        + "\n## Install\n\n```\nadb install-multiple --no-incremental -r "
        + " ".join(f'"{o.name}"' for o in outputs)
        + "\n```\n",
        encoding="utf-8",
    )
    print(f"\ninstall set: {OUT_DIR}")
    for o in outputs:
        print(f"  {o.name}  {o.stat().st_size:,} bytes")
    return 0

if __name__ == "__main__":
    sys.exit(main())
